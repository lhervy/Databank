-- =====================================================================
-- DATABANK · 05 · Security inside the pipeline
--   * least-privilege grants per role and per layer
--   * masking policies on personal data (applied by dbt post-hooks on
--     Gold tables, and directly on Bronze)
--   * row access policy: in the app, a client only sees their own rows
-- Run BEFORE the first dbt build (dbt attaches these policies).
-- =====================================================================
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE DATABANK_WH;
USE DATABASE DATABANK;

-- ---------------------------------------------------------------------
-- 1. Grants per role
-- ---------------------------------------------------------------------
GRANT USAGE ON WAREHOUSE DATABANK_WH TO ROLE DATABANK_ENGINEER;
GRANT USAGE ON WAREHOUSE DATABANK_WH TO ROLE DATABANK_ANALYST;
GRANT USAGE ON WAREHOUSE DATABANK_WH TO ROLE DATABANK_COMPLIANCE;
GRANT USAGE ON WAREHOUSE DATABANK_WH TO ROLE DATABANK_CLIENT_APP;
GRANT USAGE ON DATABASE DATABANK TO ROLE DATABANK_ENGINEER;
GRANT USAGE ON DATABASE DATABANK TO ROLE DATABANK_ANALYST;
GRANT USAGE ON DATABASE DATABANK TO ROLE DATABANK_COMPLIANCE;
GRANT USAGE ON DATABASE DATABANK TO ROLE DATABANK_CLIENT_APP;

-- Engineer: every layer, read-only outside dbt (dbt runs as the owner role)
GRANT USAGE ON ALL SCHEMAS IN DATABASE DATABANK TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON ALL TABLES IN DATABASE DATABANK TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON ALL VIEWS IN DATABASE DATABANK TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA DATABANK.RAW          TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA DATABANK.STAGING      TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA DATABANK.STAGING      TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA DATABANK.INTERMEDIATE TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA DATABANK.MARTS        TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA DATABANK.MARTS        TO ROLE DATABANK_ENGINEER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DATABANK.MARTS        TO ROLE DATABANK_ENGINEER;

-- Analyst & Compliance: Gold only
GRANT USAGE ON SCHEMA DATABANK.MARTS TO ROLE DATABANK_ANALYST;
GRANT USAGE ON SCHEMA DATABANK.MARTS TO ROLE DATABANK_COMPLIANCE;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA DATABANK.MARTS TO ROLE DATABANK_ANALYST;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA DATABANK.MARTS TO ROLE DATABANK_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DATABANK.MARTS TO ROLE DATABANK_ANALYST;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA DATABANK.MARTS TO ROLE DATABANK_COMPLIANCE;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA DATABANK.MARTS TO ROLE DATABANK_COMPLIANCE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DATABANK.MARTS TO ROLE DATABANK_COMPLIANCE;

-- Client app: schema usage only; dbt grants SELECT on the app_* views only
GRANT USAGE ON SCHEMA DATABANK.MARTS TO ROLE DATABANK_CLIENT_APP;

-- ---------------------------------------------------------------------
-- 2. Masking policies
--    ACCOUNTADMIN is the dbt owner role: it must read clear values to
--    build Gold. Engineers and analysts never see identities.
-- ---------------------------------------------------------------------
CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_PII_TEXT AS (val STRING) RETURNS STRING ->
    CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'DATABANK_COMPLIANCE') THEN val ELSE '*** masked ***' END;

CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_IBAN AS (val STRING) RETURNS STRING ->
    CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'DATABANK_COMPLIANCE') THEN val
         ELSE 'FR76 **** **** **** ' || RIGHT(val, 4) END;

CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_BIRTH_DATE AS (val DATE) RETURNS DATE ->
    CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'DATABANK_COMPLIANCE') THEN val
         ELSE DATE_TRUNC('year', val) END;

-- Change log rows are JSON: strip the personal fields for other roles
CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MP_PII_VARIANT AS (val VARIANT) RETURNS VARIANT ->
    CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'DATABANK_COMPLIANCE') THEN val
         ELSE OBJECT_DELETE(val, 'FIRST_NAME', 'LAST_NAME', 'EMAIL', 'IBAN', 'BIRTH_DATE') END;

-- Bronze: attach directly (these tables are never recreated)
ALTER TABLE CORE_BANKING.CLIENTS MODIFY COLUMN first_name SET MASKING POLICY GOVERNANCE.MP_PII_TEXT FORCE;
ALTER TABLE CORE_BANKING.CLIENTS MODIFY COLUMN last_name  SET MASKING POLICY GOVERNANCE.MP_PII_TEXT FORCE;
ALTER TABLE CORE_BANKING.CLIENTS MODIFY COLUMN email      SET MASKING POLICY GOVERNANCE.MP_PII_TEXT FORCE;
ALTER TABLE CORE_BANKING.CLIENTS MODIFY COLUMN iban       SET MASKING POLICY GOVERNANCE.MP_IBAN FORCE;
ALTER TABLE CORE_BANKING.CLIENTS MODIFY COLUMN birth_date SET MASKING POLICY GOVERNANCE.MP_BIRTH_DATE FORCE;
ALTER TABLE RAW.CORE_BANKING_CHANGES MODIFY COLUMN record SET MASKING POLICY GOVERNANCE.MP_PII_VARIANT FORCE;

-- ---------------------------------------------------------------------
-- 3. Row access policy for the mobile app
--    In production the app passes the authenticated client id; here a
--    mapping table links a Snowflake user to one fictive client.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS GOVERNANCE.APP_USER_MAP (user_name STRING, client_id STRING);
INSERT INTO GOVERNANCE.APP_USER_MAP
SELECT CURRENT_USER(), 'C000042'
WHERE NOT EXISTS (SELECT 1 FROM GOVERNANCE.APP_USER_MAP WHERE user_name = CURRENT_USER());

CREATE ROW ACCESS POLICY IF NOT EXISTS GOVERNANCE.RAP_OWN_CLIENT_ONLY
AS (row_client_id STRING) RETURNS BOOLEAN ->
    CURRENT_ROLE() <> 'DATABANK_CLIENT_APP'
    OR EXISTS (SELECT 1 FROM DATABANK.GOVERNANCE.APP_USER_MAP m
               WHERE m.user_name = CURRENT_USER() AND m.client_id = row_client_id);
